-- Local-development schema for the embedded H2 database (MySQL compatibility mode).
-- Production keeps using backend/src/main/resources/schema.sql (MySQL 8).
CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    user_id VARCHAR(50) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    recovery_code_hash VARCHAR(255) NOT NULL,
    token_version BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_app_user_username UNIQUE (username),
    CONSTRAINT uk_app_user_user_id UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS diagram (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    mode VARCHAR(32) NOT NULL,
    user_id VARCHAR(50) NOT NULL,
    content CLOB NOT NULL,
    version BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_diagram_user_updated ON diagram (user_id, updated_at);

CREATE TABLE IF NOT EXISTS diagram_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagram_id BIGINT NOT NULL,
    user_id VARCHAR(100) NOT NULL,
    title VARCHAR(100) NOT NULL,
    mode VARCHAR(32) NOT NULL,
    content CLOB NOT NULL,
    revision_no BIGINT NOT NULL,
    change_source VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_revision_diagram ON diagram_revision (diagram_id, created_at);
